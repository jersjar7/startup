/// The league results moment, drawn by Rive (owner, 2026-11-01: "a nice
/// animation on the flutter app for league regressions and league
/// promotions. Use Rive as normal").
///
/// Same arrangement as the badge moment (badge_art.dart): the file loads
/// once at launch, nothing waits on it, and until it arrives, in every
/// widget test, and when the phone asks for reduced motion, a painter draws
/// the last frame. Rive only changes pixels; which metals, in which colours,
/// comes from here.
///
/// The artboard is generated by `mobile/rive/league/gen.py`; its contract is
/// the `League` view model and the `land` event. `league_moment_test.dart`
/// reads the markup and fails when the names here drift from it.
abstract final class LeagueArt {
  static const asset = 'assets/rive/league.riv';
  static const artboard = 'LeagueMove';
  static const stateMachine = 'Main';
  static const landEvent = 'land';

  /// The view model's properties, by name.
  static const numbers = ['move', 'from', 'to'];
  static const colors = [
    'fromFace',
    'fromRim',
    'fromInk',
    'fromRing',
    'toFace',
    'toRim',
    'toInk',
    'toRing',
    'card',
  ];

  /// `move`: which motion plays.
  static const up = 1.0;
  static const down = 2.0;
  static const stay = 3.0;

  /// The artboard's geometry, in its own units.
  static const width = 780.0;
  static const height = 1000.0;
  static const cardLeft = 36.0;
  static const cardTop = 150.0;
  static const cardRadius = 72.0;
  static const coinCentreY = 380.0;
  static const coinRadius = 150.0;
  static const wordsTop = 588.0;

  /// When the words come in, as a share of [wordsAfter].
  static const wordsAfter = Duration(milliseconds: 2400);
  static double wordsFrom(String moved) => switch (moved) {
    'up' => 72 / 144,
    'down' => 64 / 144,
    _ => 44 / 144,
  };

  static final file = ValueNotifier<rive.File?>(null);
  static Future<void>? _loading;

  static Future<void> warmUp() => _loading ??= _load();

  static Future<void> _load() async {
    try {
      file.value = await rive.File.asset(
        asset,
        riveFactory: rive.Factory.flutter,
      );
    } catch (e) {
      debugPrint('league art unavailable, the painter stays: $e');
    }
  }
}

/// Shows last week's result over everything, once. The caller marks it
/// seen.
Future<void> showLeagueMoment(
  BuildContext context,
  LeagueResult result, {
  VoidCallback? onSeeLeague,
}) {
  return Navigator.of(context, rootNavigator: true).push(
    PageRouteBuilder<void>(
      opaque: true,
      transitionDuration: const Duration(milliseconds: 220),
      reverseTransitionDuration: const Duration(milliseconds: 180),
      pageBuilder: (_, _, _) =>
          LeagueMomentScreen(result: result, onSeeLeague: onSeeLeague),
      transitionsBuilder: (_, a, _, child) =>
          FadeTransition(opacity: a, child: child),
    ),
  );
}

/// What the result says, in our voice. Never a penalty: a move down is a
/// new group at the right level, not a loss (ADR 0037, no-penalty rule).
@visibleForTesting
({String eyebrow, String title, String line}) leagueWords(LeagueResult r) {
  final where = r.place > 0 && r.size > 0
      ? '${ordinal(r.place)} of ${r.size} in ${r.from.label} last week.'
      : 'Last week in ${r.from.label}.';
  return switch (r.moved) {
    'up' => (
      eyebrow: 'MOVED UP',
      title: 'You moved up to ${r.to.label}',
      line: '$where A new week starts now, and everyone is back at zero.',
    ),
    'down' => (
      eyebrow: 'NEW LEAGUE',
      title: 'This week, ${r.to.label}',
      line:
          '$where A group nearer your pace this week. Finish in the top five '
          'to move back up.',
    ),
    _ => (
      eyebrow: 'STAYING',
      title: 'Another week in ${r.to.label}',
      line: '$where Everyone starts at zero again today.',
    ),
  };
}

class LeagueMomentScreen extends StatelessWidget {
  const LeagueMomentScreen({super.key, required this.result, this.onSeeLeague});

  final LeagueResult result;
  final VoidCallback? onSeeLeague;

  @override
  Widget build(BuildContext context) {
    final still = MediaQuery.of(context).disableAnimations;
    return Scaffold(
      backgroundColor: AppColors.fog,
      body: SafeArea(
        child: LayoutBuilder(
          builder: (context, box) => SingleChildScrollView(
            padding: const EdgeInsets.fromLTRB(16, 12, 16, 24),
            child: ConstrainedBox(
              constraints: BoxConstraints(minHeight: box.maxHeight - 36),
              // The card in the middle, the way on at the bottom (as the
              // badge moment; 13c-game-done is the closest reference).
              child: Column(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  const SizedBox.shrink(),
                  ConstrainedBox(
                    constraints: const BoxConstraints(maxWidth: 420),
                    child: LeagueMoveCard(result: result, animate: !still),
                  ),
                  Padding(
                    padding: const EdgeInsets.only(top: 24),
                    child: Row(
                      children: [
                        if (onSeeLeague != null) ...[
                          TextAction(
                            label: 'Not now',
                            onTap: () => Navigator.of(context).pop(),
                          ),
                          const SizedBox(width: 14),
                        ],
                        Expanded(
                          child: PillButton(
                            label: onSeeLeague != null
                                ? 'See your league'
                                : 'Carry on',
                            onTap: () {
                              Navigator.of(context).pop();
                              onSeeLeague?.call();
                            },
                          ),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}

/// Binds the artboard's view model to a result.
class _Binding {
  _Binding(rive.File file, LeagueResult r)
    : controller = rive.RiveWidgetController(
        file,
        artboardSelector: rive.ArtboardSelector.byName(LeagueArt.artboard),
        stateMachineSelector: rive.StateMachineSelector.byName(
          LeagueArt.stateMachine,
        ),
      ) {
    _vmi = controller.dataBind(rive.DataBind.auto());
    final from = LeagueCoinColors.of(r.from);
    final to = LeagueCoinColors.of(r.to);
    final colors = {
      'fromFace': from.face,
      'fromRim': from.rim,
      'fromInk': from.ink,
      'fromRing': from.ink.withValues(alpha: 0.45),
      'toFace': to.face,
      'toRim': to.rim,
      'toInk': to.ink,
      'toRing': to.ink.withValues(alpha: 0.45),
      // The card follows the mode; the coin on it does not.
      'card': AppColors.cream,
    };
    for (final e in colors.entries) {
      _props.add(_vmi.color(e.key)!..value = e.value);
    }
    _props.add(_vmi.number('from')!..value = r.from.index.toDouble());
    _props.add(_vmi.number('to')!..value = r.to.index.toDouble());
    // Last, so the motion starts with every colour already in place.
    _props.add(
      _vmi.number('move')!
        ..value = switch (r.moved) {
          'up' => LeagueArt.up,
          'down' => LeagueArt.down,
          _ => LeagueArt.stay,
        },
    );
  }

  final rive.RiveWidgetController controller;
  late final rive.ViewModelInstance _vmi;
  final List<rive.ViewModelInstanceValue> _props = [];

  void dispose() {
    for (final p in _props) {
      p.dispose();
    }
    _vmi.dispose();
    controller.dispose();
  }
}

/// The card: the Rive coin turning into this week's, with the words set
/// over it by Flutter so they are real text.
class LeagueMoveCard extends StatefulWidget {
  const LeagueMoveCard({super.key, required this.result, this.animate = true});

  final LeagueResult result;
  final bool animate;

  @override
  State<LeagueMoveCard> createState() => _LeagueMoveCardState();
}

class _LeagueMoveCardState extends State<LeagueMoveCard>
    with SingleTickerProviderStateMixin {
  _Binding? _binding;
  late final AnimationController _words = AnimationController(
    vsync: this,
    duration: LeagueArt.wordsAfter,
  );

  @override
  void initState() {
    super.initState();
    final file = LeagueArt.file.value;
    if (widget.animate && file != null) {
      final b = _Binding(file, widget.result);
      b.controller.stateMachine.addEventListener(_onEvent);
      _binding = b;
      _words.forward();
    } else {
      _words.value = 1;
      HapticFeedback.lightImpact();
    }
  }

  void _onEvent(rive.Event event) {
    if (event.name != LeagueArt.landEvent) return;
    // The weight of a promotion; a light touch for anything else.
    if (widget.result.moved == 'up') {
      HapticFeedback.mediumImpact();
    } else {
      HapticFeedback.lightImpact();
    }
  }

  @override
  void dispose() {
    _binding?.controller.stateMachine.removeEventListener(_onEvent);
    _binding?.dispose();
    _words.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AspectRatio(
      aspectRatio: LeagueArt.width / LeagueArt.height,
      child: LayoutBuilder(
        builder: (context, box) {
          final k = box.maxWidth / LeagueArt.width;
          return Stack(
            children: [
              Positioned.fill(
                child: _binding != null
                    ? rive.RiveWidget(
                        controller: _binding!.controller,
                        fit: rive.Fit.contain,
                        hitTestBehavior: rive.RiveHitTestBehavior.none,
                      )
                    : CustomPaint(painter: _AtRest(widget.result.to)),
              ),
              Positioned(
                left: (LeagueArt.cardLeft + 36) * k,
                right: (LeagueArt.cardLeft + 36) * k,
                top: LeagueArt.wordsTop * k,
                child: AnimatedBuilder(
                  animation: _words,
                  builder: (context, _) => _Words(
                    result: widget.result,
                    t: _words.value,
                    scale: k,
                  ),
                ),
              ),
            ],
          );
        },
      ),
    );
  }
}

class _Words extends StatelessWidget {
  const _Words({required this.result, required this.t, required this.scale});

  final LeagueResult result;
  final double t;
  final double scale;

  double _beat(double from, double len) =>
      Curves.easeOutQuart.transform(((t - from) / len).clamp(0.0, 1.0));

  Widget _rise(double v, Widget child) => Opacity(
    opacity: v,
    child: Transform.translate(offset: Offset(0, 18 * (1 - v)), child: child),
  );

  @override
  Widget build(BuildContext context) {
    final w = leagueWords(result);
    final f = LeagueArt.wordsFrom(result.moved);
    final k = scale;
    return Semantics(
      container: true,
      liveRegion: true,
      label: '${w.title}. ${w.line}',
      child: ExcludeSemantics(
        child: Column(
          children: [
            _rise(
              _beat(f, 0.12),
              Text(
                w.eyebrow,
                style: AppTheme.eyebrow(
                  color: result.moved == 'up'
                      ? AppColors.forest
                      : AppColors.mutedOnLight,
                ),
              ),
            ),
            SizedBox(height: 10 * k),
            _rise(
              _beat(f + 0.04, 0.16),
              Text(
                w.title,
                textAlign: TextAlign.center,
                maxLines: 2,
                style: AppTheme.display(
                  size: (64 * k).clamp(26.0, 36.0),
                  height: 1.0,
                  tracking: -0.04,
                ),
              ),
            ),
            SizedBox(height: 12 * k),
            _rise(
              _beat(f + 0.12, 0.14),
              Text(
                w.line,
                textAlign: TextAlign.center,
                maxLines: 3,
                style: AppTheme.body(
                  size: (32 * k).clamp(14.0, 17.0),
                  color: AppColors.mutedOnLight,
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// The last frame, painted: the card and this week's coin.
class _AtRest extends CustomPainter {
  const _AtRest(this.metal);

  final LeagueMetal metal;

  @override
  void paint(Canvas canvas, Size size) {
    final k = size.width / LeagueArt.width;
    canvas.save();
    canvas.scale(k);
    canvas.drawRRect(
      RRect.fromLTRBR(
        LeagueArt.cardLeft,
        LeagueArt.cardTop,
        LeagueArt.width - LeagueArt.cardLeft,
        LeagueArt.height - 36,
        const Radius.circular(LeagueArt.cardRadius),
      ),
      Paint()..color = AppColors.cream,
    );
    paintLeagueCoin(
      canvas,
      const Offset(LeagueArt.width / 2, LeagueArt.coinCentreY),
      LeagueArt.coinRadius,
      metal,
    );
    canvas.restore();
  }

  @override
  bool shouldRepaint(_AtRest old) => old.metal != metal;
}
