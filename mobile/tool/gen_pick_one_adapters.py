#!/usr/bin/env python3
"""Writes pack adapters for built-in games that use the standard pick-one
screen (ADR 0030, phase 3). Every string is lifted from the game's own file,
never retyped, and the screen must match the template exactly or the game is
refused: the parity test then compares the result pixel for pixel.

    python3 tool/gen_pick_one_adapters.py <out.dart> <game_file.dart>...
"""
import re
import sys
from pathlib import Path

GAMES = Path('lib/features/games')
TEMPLATE = Path('lib/features/packs/games/pick_one_game.dart')


def balanced(src, start):
    """The text from src[start] (an opening paren) to its closing paren."""
    depth = 0
    for i in range(start, len(src)):
        if src[i] == '(':
            depth += 1
        elif src[i] == ')':
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
    raise ValueError('unbalanced')


def string_at(src, start):
    """A run of adjacent Dart string literals starting at src[start:]."""
    m = re.match(r"\s*((?:'(?:[^'\\]|\\.)*'\s*)+)", src[start:])
    return m.group(1).strip()


def choice_block(src):
    return src[src.index('class _Choice'):]


def screen_shape(src):
    """The game's build method with everything a game may vary blanked
    out: its strings, its brief, its panel height and its painter. Two
    games with the same shape draw the same screen around their content."""
    body = src[src.index('Widget build(BuildContext context) {'):src.index('class _Choice')]
    p = body.index('painter: ') + len('painter: ')
    name = re.match(r'\w+', body[p:]).group(0)
    body = body.replace(name + balanced(body, p + len(name)), 'PAINTER')
    body = re.sub(r"(?:'(?:[^'\\]|\\.)*'\s*)+", 'STR ', body)
    body = re.sub(r'brief: \w+,', 'brief: BRIEF,', body)
    body = re.sub(r'Container\(\s*height: \d+,', 'Container(height: H,', body)
    # The one sanctioned variant: answers that are an enum's labels.
    body = body.replace('for (final option in ', 'for (OPTIONS in ')
    return re.sub(r'\s+', ' ', body)


SHAPE = None


def adapter(path):
    global SHAPE
    src = path.read_text()
    if choice_block(src) != choice_block(TEMPLATE.read_text()):
        raise SystemExit(f'{path}: answer buttons differ from the template')
    if SHAPE is None:
        SHAPE = screen_shape((GAMES / 'when_can_it_start_game.dart').read_text())
    if 'for (final option in ' not in src and screen_shape(src) != SHAPE:
        raise SystemExit(f'{path}: the screen differs from the standard pick-one')
    game_id = re.search(r"gameId: '([a-z0-9-]+)'", src).group(1)
    chapter = re.search(r"chapterId: '([a-z0-9-]+)'", src).group(1)
    rounds = re.search(r'total: (\w+)\.length', src).group(1)
    done = src.index('return BoardDone(')
    title = string_at(src, src.index('title:', done) + 6)
    closing = string_at(src, src.index('closing:', done) + 8)
    shell = src.index('return BoardShell(')
    brief = re.search(r'brief: (\w+),', src[shell:]).group(1)
    overline = string_at(src, src.index('Text(', shell) + 5)
    height = int(re.search(r'Container\(\s*height: (\d+),', src[shell:]).group(1))
    p = src.index('painter: ', shell) + len('painter: ')
    name = re.match(r'\w+', src[p:]).group(0)
    painter = name + balanced(src, p + len(name))
    titles = re.search(
        r"title: _session\.correct! \? ('[^']*') : ('[^']*'),", src).group(1, 2)
    enum = re.search(r'for \(final option in (\w+)\.values\)', src)
    if enum:
        label = re.search(r'label: (\w+)\.label\(option\)', src).group(1)
        options = f'[for (final o in {enum.group(1)}.values) {label}.label(o)]'
        answer = f'{enum.group(1)}.values.indexOf(r.answer)'
    else:
        options, answer = 'r.options', 'r.answer'
    imports = sorted({f"package:mobile/features/games/{path.name}"} | {
        f"package:mobile/features/games/{m}"
        for m in re.findall(r"^import '([a-z0-9_]+\.dart)';", src, re.M)})
    fn = re.sub(r'-(\w)', lambda m: m.group(1).upper(), game_id)
    body = f'''Map<String, Object?> {fn}() => pickOne(
  id: '{game_id}',
  chapter: '{chapter}',
  title: {title},
  closing: {closing},
  overline: {overline},
  right: {titles[0]},
  wrong: {titles[1]},
  figureHeight: {height},
  brief: briefJson({brief}, '{brief}'),
  rounds: [
    for (final r in {rounds})
      (
        subject: r.subject,
        asked: r.asked,
        options: {options},
        answer: {answer},
        why: r.why,
        source: r.source,
        draw: (bool answered) => {painter}.paint,
      ),
  ],
);
'''
    return game_id, fn, imports, body


def main():
    out = Path(sys.argv[1])
    made = [adapter(GAMES / f) for f in sys.argv[2:]]
    imports = sorted({i for _, _, imp, _ in made for i in imp})
    lines = [
        '// Generated by tool/gen_pick_one_adapters.py. Do not edit by hand.',
        '// ignore_for_file: directives_ordering, unused_import',
        '',
        *[f"import '{i}';" for i in imports],
        '',
        "import 'pick_one_adapter.dart';",
        "import 'builder.dart';",
        '',
    ]
    for _, _, _, body in made:
        lines.append(body)
    lines.append('/// Every game in this file, by id.')
    lines.append('final adapters = <String, Map<String, Object?> Function()>{')
    for game_id, fn, _, _ in made:
        lines.append(f"  '{game_id}': {fn},")
    lines.append('};')
    out.write_text('\n'.join(lines) + '\n')


main()
